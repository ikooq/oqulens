// Автоматическая методическая записка (без ИИ) на русском или казахском.
import { Analysis, buildInsights, hoursReason } from "./analytics";
import { makeFmt } from "./format";
import { Lang, tr } from "./i18n";
import { ReportContext, schoolList } from "./report";

export function buildReport(a: Analysis, ctx: ReportContext, lang: Lang = "ru"): string {
  const t = (ru: string, kk: string) => tr(lang, ru, kk);
  const f = makeFmt(lang);
  const { pct, share, pp } = f;
  const L: string[] = [];
  const CI = t("95% ДИ", "95% СА");

  L.push(t("# Методическая записка", "# Әдістемелік жазба"));
  L.push(`**${ctx.title}** · ${ctx.scope} · ${ctx.date}`);
  L.push(
    t(
      `Охват: ${f.nStudents(a.meta.nStudents)}, ${f.nSchools(a.meta.nSchools)}, ${f.nClasses(a.meta.nClasses)}. Источник: результаты суммативного оценивания за раздел (СОР).`,
      `Қамту: ${f.nStudents(a.meta.nStudents)}, ${f.nSchools(a.meta.nSchools)}, ${f.nClasses(a.meta.nClasses)}. Дереккөз: бөлім бойынша жиынтық бағалау (БЖБ) нәтижелері.`,
    ) + (ctx.synthetic ? t(" *Расчёт выполнен на синтетических демо-данных.*", " *Есеп синтетикалық демо-деректер бойынша жасалды.*") : ""),
  );

  L.push(t("## 1. Главное", "## 1. Негізгі қорытындылар"));
  for (const i of buildInsights(a, lang)) L.push(`- **${i.title.replace(/\.$/, "")}.** ${i.text.trim()}`);

  L.push(t("## 2. Трудные для усвоения разделы", "## 2. Меңгеру қиын бөлімдер"));
  const risky = a.sections.filter((s) => s.status !== "ok").sort((x, y) => x.mean - y.mean);
  if (!risky.length) L.push(t("Все разделы освоены на приемлемом уровне.", "Барлық бөлім қолайлы деңгейде меңгерілген."));
  for (const s of risky) {
    const diag = s.systemic
      ? t("проблема системная: раздел проседает во всех школах", "мәселе жүйелі: бөлім барлық мектепте төмен")
      : s.uneven
        ? t("результат сильно зависит от школы — вопрос качества преподавания", "нәтиже мектепке қатты тәуелді — оқыту сапасының мәселесі")
        : t("требует внимания", "назар аударуды қажет етеді");
    L.push(
      t(
        `- **${s.name}** — средний результат ${pct(s.mean)} (${CI} ${pct(s.ciLo)}–${pct(s.ciHi)}), ниже 40% — у ${share(s.lowShare)} учащихся; ${diag}.`,
        `- **${s.name}** — орташа нәтиже ${pct(s.mean)} (${CI} ${pct(s.ciLo)}–${pct(s.ciHi)}), оқушылардың ${share(s.lowShare)}-ы 40%-дан төмен; ${diag}.`,
      ),
    );
  }
  for (const l of a.prereqs.filter((l) => a.sections.find((s) => s.name === l.to)?.status !== "ok")) {
    L.push(
      t(
        `- Связь «${l.from}» → «${l.to}»: среди не освоивших «${l.from}» провалили «${l.to}» ${share(l.failIfWeak)} учащихся, среди освоивших — ${share(l.failIfStrong)}.`,
        `- «${l.from}» → «${l.to}» байланысы: «${l.from}» бөлімін меңгермегендердің ${share(l.failIfWeak)}-ы «${l.to}» бөлімін орындай алмады, меңгергендердің арасында — ${share(l.failIfStrong)}.`,
      ),
    );
  }

  L.push(t("## 3. Школы: где нужна поддержка и чей опыт тиражировать", "## 3. Мектептер: қайда қолдау керек және кімнің тәжірибесін тарату керек"));
  const weak = schoolList(a, "below");
  const strong = schoolList(a, "above");
  if (!weak.length && !strong.length)
    L.push(t("Существенных различий между школами с учётом состава учеников не выявлено.", "Оқушылар құрамын ескергенде мектептер арасында елеулі айырмашылық анықталмады."));
  else {
    const nb = a.schools.filter((p) => p.vaFlag === "below").length;
    const na = a.schools.filter((p) => p.vaFlag === "above").length;
    L.push(
      t(
        `Школы сравниваются не по сырым баллам, а с ожидаемым результатом для их учеников (стартовый уровень, город/село, учебник). Ниже ожидаемого — ${f.nSchools(nb)}, выше — ${f.nSchools(na)}.`,
        `Мектептер шикі балл бойынша емес, олардың оқушылары үшін күтілетін нәтижемен салыстырылады (бастапқы деңгей, қала/ауыл, оқулық). Күтілгеннен төмен — ${f.nSchools(nb)}, жоғары — ${f.nSchools(na)}.`,
      ),
    );
    for (const p of weak.slice(0, 5)) {
      const secs = p.sections.filter((s) => s.flag === "below").map((s) => `«${s.section}»`);
      L.push(
        t(
          `- **${p.school}** (${p.district}): ${pp(p.valueAdded)} к ожидаемому${secs.length ? `; проседают ${secs.join(", ")}` : ""}.`,
          `- **${p.school}** (${p.district}): күтілгенге қатысты ${pp(p.valueAdded)}${secs.length ? `; төмен бөлімдер: ${secs.join(", ")}` : ""}.`,
        ),
      );
    }
    if (strong.length)
      L.push(
        t("Опорные школы для обмена опытом: ", "Тәжірибе алмасуға арналған тірек мектептер: ") +
          strong
            .slice(0, 5)
            .map((p) => `${p.school} (${p.district}, ${pp(p.valueAdded)})`)
            .join("; ") +
          ".",
      );
  }

  L.push(t("## 4. Эффективность учебников", "## 4. Оқулықтардың тиімділігі"));
  const tb = a.textbooks;
  if (!tb.ok)
    L.push(
      t(
        "Недостаточно данных для сравнения учебников (нужно минимум 2 учебника, на каждый — от 3 школ).",
        "Оқулықтарды салыстыруға дерек жеткіліксіз (кемінде 2 оқулық, әрқайсысына 3 мектептен керек).",
      ),
    );
  else {
    for (const r of [...tb.rows].sort((x, y) => y.adjusted.mean - x.adjusted.mean))
      L.push(
        t(
          `- **${r.name}**: ${f.nSchools(r.nSchools)}, сырой средний балл ${pct(r.naive.mean)}, с поправкой на состав учеников — ${pct(r.adjusted.mean)} (${CI} ${pct(r.adjusted.lo)}–${pct(r.adjusted.hi)}).`,
          `- **${r.name}**: ${f.nSchools(r.nSchools)}, шикі орташа балл ${pct(r.naive.mean)}, оқушылар құрамын ескергенде — ${pct(r.adjusted.mean)} (${CI} ${pct(r.adjusted.lo)}–${pct(r.adjusted.hi)}).`,
        ),
      );
    if (tb.rankChanged)
      L.push(
        t(
          `Рейтинг по сырым баллам (${tb.naiveRank.join(" > ")}) отличается от рейтинга с поправкой (${tb.adjustedRank.join(" > ")}): учебники используются в школах с разным стартовым уровнем учеников.`,
          `Шикі балл бойынша рейтинг (${tb.naiveRank.join(" > ")}) түзетілген рейтингтен (${tb.adjustedRank.join(" > ")}) өзгеше: оқулықтар оқушыларының бастапқы деңгейі әртүрлі мектептерде қолданылады.`,
        ),
      );
    L.push(
      tb.bestSignificant
        ? t(`Лидер — «${tb.best}», отрыв ${pp(tb.bestMargin)} статистически надёжен.`, `Көшбасшы — «${tb.best}», ${pp(tb.bestMargin)} айырма статистикалық тұрғыда сенімді.`)
        : t(
            `Отрыв лидера («${tb.best}», ${pp(tb.bestMargin)}) в пределах погрешности — менять учебник только на этом основании не рекомендуется.`,
            `Көшбасшының айырмасы («${tb.best}», ${pp(tb.bestMargin)}) қателік шегінде — тек осы негізде оқулықты ауыстыру ұсынылмайды.`,
          ),
    );
    for (const l of tb.lags)
      L.push(
        t(
          `- Слабая глава: «${l.textbook}» в разделе «${l.section}» — ${pp(l.diffVsBest)} к лучшему учебнику при равном составе учеников.`,
          `- Әлсіз тарау: «${l.textbook}», «${l.section}» бөлімі — оқушылар құрамы бірдей болғанда ең жақсы оқулыққа қатысты ${pp(l.diffVsBest)}.`,
        ),
      );
  }

  L.push(t("## 5. Рекомендации по распределению учебных часов", "## 5. Оқу сағаттарын бөлу бойынша ұсыныстар"));
  const h = a.hours;
  if (!h.ok)
    L.push(
      t(
        "Нет данных о фактических часах по классам — рекомендации по часам недоступны.",
        "Сыныптар бойынша нақты сағаттар туралы дерек жоқ — сағат бойынша ұсыныстар қолжетімсіз.",
      ),
    );
  else {
    L.push(
      t(
        `Общий объём (${h.totalPlanned} ч) сохраняется, перераспределяется ${h.movedHours} ч:`,
        `Жалпы көлем (${h.totalPlanned} сағат) сақталады, ${h.movedHours} сағат қайта бөлінеді:`,
      ),
    );
    for (const s of h.sections.filter((s) => s.delta !== 0))
      L.push(`- **${s.name}**: ${s.planned} → ${s.recommended} ${t("ч", "сағат")} (${f.signed(s.delta)}). ${hoursReason(s, lang)}`);
    L.push(
      t(
        `Ожидаемый эффект: средний результат ${pct(h.meanBefore)} → ${f.fmt1(h.meanAfter)}% (${pp(h.meanAfter - h.meanBefore)}; по консервативной оценке ${pp(
          h.meanAfterConservative - h.meanBefore,
        )}), доля результатов ниже 40% — с ${share(h.lowBefore)} до ${share(h.lowAfter)}.`,
        `Күтілетін әсер: орташа нәтиже ${pct(h.meanBefore)} → ${f.fmt1(h.meanAfter)}% (${pp(h.meanAfter - h.meanBefore)}; сақ бағалау бойынша ${pp(
          h.meanAfterConservative - h.meanBefore,
        )}), 40%-дан төмен нәтижелер үлесі ${share(h.lowBefore)}-дан ${share(h.lowAfter)}-ға дейін.`,
      ),
    );
  }

  L.push(t("## 6. План действий на следующую четверть", "## 6. Келесі тоқсанға арналған іс-шаралар жоспары"));
  let n = 1;
  const root = a.prereqs.find((l) => a.sections.find((s) => s.name === l.to)?.status === "hard");
  if (root)
    L.push(
      t(
        `${n++}. Перед изучением «${root.to}» провести диагностический срез по «${root.from}» и 1–2 урока повторения для учащихся с результатом ниже 40%.`,
        `${n++}. «${root.to}» бөлімін оқымас бұрын «${root.from}» бойынша диагностикалық қима өткізіп, нәтижесі 40%-дан төмен оқушыларға 1–2 қайталау сабағын беру.`,
      ),
    );
  for (const l of tb.lags.slice(0, 2))
    L.push(
      t(
        `${n++}. Школам, работающим по «${l.textbook}», подготовить дополнительные материалы к разделу «${l.section}».`,
        `${n++}. «${l.textbook}» бойынша оқытатын мектептерге «${l.section}» бөліміне қосымша материалдар дайындау.`,
      ),
    );
  const uneven = a.sections.find((s) => s.uneven);
  if (uneven && uneven.bestSchools.length) {
    const hosts = uneven.bestSchools
      .slice(0, 2)
      .map((s) => `«${s.school}» (${s.district})`)
      .join(t(" и ", " және "));
    const guests = uneven.worstSchools
      .slice(0, 3)
      .map((s) => `«${s.school}»`)
      .join(", ");
    L.push(
      t(
        `${n++}. По разделу «${uneven.name}» организовать методический семинар с участием ${hosts} для школ с результатом ниже ожидаемого: ${guests}.`,
        `${n++}. «${uneven.name}» бөлімі бойынша ${hosts} қатысуымен нәтижесі күтілгеннен төмен мектептерге әдістемелік семинар ұйымдастыру: ${guests}.`,
      ),
    );
  }
  // от самой отстающей школы к менее отстающим
  const broad = a.schools.filter((p) => p.vaFlag === "below" && p.sections.filter((s) => s.flag === "below").length >= 3).reverse();
  if (broad.length) {
    const list = broad
      .slice(0, 5)
      .map((p) => `«${p.school}»`)
      .join(", ");
    L.push(
      t(
        `${n++}. Закрепить методиста и организовать наставничество для школ с отставанием по большинству разделов: ${list}.`,
        `${n++}. Бөлімдердің көпшілігі бойынша артта қалған мектептерге әдіскер бекітіп, тәлімгерлік ұйымдастыру: ${list}.`,
      ),
    );
  }
  if (h.ok && h.movedHours > 0)
    L.push(
      t(
        `${n++}. Апробировать новое распределение часов в 5–10 школах и сравнить результаты следующего СОР с остальными школами.`,
        `${n++}. Сағаттардың жаңа бөлінуін 5–10 мектепте сынақтан өткізіп, келесі БЖБ нәтижелерін қалған мектептермен салыстыру.`,
      ),
    );
  L.push(t(`${n++}. Повторить анализ после следующего СОР и отследить динамику.`, `${n++}. Келесі БЖБ-дан кейін талдауды қайталап, динамиканы бақылау.`));

  L.push(t("## 7. Ограничения", "## 7. Шектеулер"));
  L.push(
    t(
      "- Учебники выбираются школами не случайно. Мы учитываем стартовый уровень учеников, тип местности и язык обучения, но другие различия между школами могут влиять на результат.",
      "- Оқулықтарды мектептер кездейсоқ таңдамайды. Біз оқушылардың бастапқы деңгейін, елді мекен түрін және оқыту тілін ескереміз, бірақ мектептер арасындағы басқа айырмашылықтар да нәтижеге әсер етуі мүмкін.",
    ),
  );
  L.push(
    t(
      "- Эффект часов оценён по естественным различиям между классами; прогноз нужно подтвердить пилотом.",
      "- Сағаттардың әсері сыныптар арасындағы табиғи айырмашылықтар бойынша бағаланды; болжамды пилоттық жобамен растау қажет.",
    ),
  );
  L.push(
    t(
      "- Оценка школ относительно ожидаемого — инструмент адресной поддержки и обмена опытом, а не основание для взысканий.",
      "- Мектептерді күтілгенмен салыстыра бағалау — атаулы қолдау мен тәжірибе алмасу құралы, жазалау негізі емес.",
    ),
  );
  if (ctx.synthetic)
    L.push(
      t(
        "- Все цифры получены на синтетических демо-данных и не описывают реальные школы.",
        "- Барлық сандар синтетикалық демо-деректерден алынған және нақты мектептерді сипаттамайды.",
      ),
    );
  return L.join("\n\n");
}
